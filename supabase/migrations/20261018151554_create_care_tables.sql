-- 新版值班系統（跟舊版 cats / notices / medicines / regulars 並行，舊表完全不動）
--   cat_profiles   貓咪          /admin/cat-profiles
--   diet_items     飲食管理      /admin/diet
--   medical_items  醫療管理      /admin/medical
--   todo_items     值班待辦管理  /admin/todos
--   shifts         值班記錄表    /shift
--   shift_comments 每隻貓的留言

-- updated_at 由資料庫自動更新，程式不用自己帶
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ── 貓咪 ───────────────────────────────────────────
create table public.cat_profiles (
  id          bigint generated by default as identity primary key,
  name        text not null,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  adopted     boolean not null default false,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ── 飲食／醫療／待辦 ───────────────────────────────
-- 適用對象：cat_id 有值 = 那隻貓；location 有值 = 那個位置的貓；兩個都空 = 全員
-- 期間：start_date / end_date 空代表不限
create table public.diet_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  category    text not null check (category in ('乾乾', '罐罐', '補充', '其他')),
  content     text not null,
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  check (cat_id is null or location is null),
  check (start_date is null or end_date is null or start_date <= end_date)
);

create table public.medical_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  category    text not null check (category in ('醫療', '吃藥', '其他')),
  treatment   text not null,
  reason      text,
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  check (cat_id is null or location is null),
  check (start_date is null or end_date is null or start_date <= end_date)
);

create table public.todo_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  content     text not null,
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  check (cat_id is null or location is null),
  check (start_date is null or end_date is null or start_date <= end_date)
);

create index diet_items_cat_id_idx    on public.diet_items (cat_id);
create index medical_items_cat_id_idx on public.medical_items (cat_id);
create index todo_items_cat_id_idx    on public.todo_items (cat_id);

-- ── 值班記錄 ───────────────────────────────────────
-- 一班一筆。cats / tasks 是這一班的快照，用物件（以 id 為 key）而不是陣列，
-- 之後寫入時只更新改動的那一格，兩人同時改不同的貓不會互相覆蓋。
create table public.shifts (
  id          bigint generated by default as identity primary key,
  date        date not null,
  shift       text not null check (shift in ('morning', 'night')),
  member      text,
  note        text,
  cats        jsonb not null default '{}'::jsonb,
  tasks       jsonb not null default '{}'::jsonb,
  updated_by  uuid references auth.users (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (date, shift)
);

-- 只新增、不覆寫，所以獨立一張表，不放進 shifts 的 jsonb
create table public.shift_comments (
  id           bigint generated by default as identity primary key,
  shift_id     bigint not null references public.shifts (id) on delete cascade,
  cat_id       bigint not null references public.cat_profiles (id) on delete cascade,
  tab          text not null check (tab in ('arrive', 'care', 'meds', 'leave', 'todo')),
  body         text not null,
  for_next     boolean not null default false,
  author_name  text,
  created_by   uuid references auth.users (id) on delete set null,
  created_at   timestamptz not null default now()
);

create index shift_comments_shift_id_idx on public.shift_comments (shift_id);

-- ── updated_at trigger ─────────────────────────────
create trigger set_updated_at before update on public.cat_profiles  for each row execute function public.set_updated_at();
create trigger set_updated_at before update on public.diet_items    for each row execute function public.set_updated_at();
create trigger set_updated_at before update on public.medical_items for each row execute function public.set_updated_at();
create trigger set_updated_at before update on public.todo_items    for each row execute function public.set_updated_at();
create trigger set_updated_at before update on public.shifts        for each row execute function public.set_updated_at();

-- ── RLS ────────────────────────────────────────────
