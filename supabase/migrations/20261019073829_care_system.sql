-- updated_at 由資料庫自動更新，程式不用自己帶
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ── 貓咪 ───────────────────────────────────────────
-- nicknames：暱稱，可以好幾個。avatar_path：頭像（Storage 的 avatars bucket，公開）。coats：花色，可多選（清單在 composables/catTraits.js）。
-- neutered：null = 不確定。birth_month：預估生日，只記到月（存那個月的 1 號）
create table public.cat_profiles (
  id           bigint generated by default as identity primary key,
  name         text not null,
  nicknames    text[] not null default '{}',
  location     text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  adopted      boolean not null default false,
  sort_order   integer,
  avatar_path  text,
  coats        text[] not null default '{}' check (coats <@ array['虎斑', '白底虎斑', '橘貓', '黑貓', '白貓', '灰貓', '賓士', '乳牛', '三花', '玳瑁', '橘白', '灰白', '其他']),
  sex          text check (sex in ('公', '母')),
  neutered     boolean,
  coat_length  text check (coat_length in ('短毛', '長毛')),
  arrived_on   date,
  birth_month  date,
  notes        text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ── 飲食／醫療／收尾／觀察 ─────────────────────────
-- 對象：cat_id 有值 = 那隻貓；location 有值 = 那個位置；兩個都空 = 全員（不能同時有值）
-- 期間：start_date / end_date 空代表不限。刪掉貓會連帶刪掉牠的項目，不會變成全員

-- 飲食：只看不打勾，只有「隨餐藥」（拌進飯裡、放碗就可以走）要在備餐分頁打勾。
-- 「放風」是長期固定放風：期間內新開的班，這隻貓的放風預設打開
create table public.diet_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  category    text not null check (category in ('乾乾', '罐罐', '隨餐藥', '補充品', '放風', '其他')),
  content     text not null,
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint diet_items_target_check check (cat_id is null or location is null),
  constraint diet_items_period_check check (start_date is null or end_date is null or start_date <= end_date)
);

-- 醫療：醫療、餵藥（親手讓牠吃下去）、外用（擦、點、噴），都在醫療分頁打勾
create table public.medical_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  category    text not null check (category in ('醫療', '餵藥', '外用')),
  treatment   text not null,
  reason      text,
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint medical_items_target_check check (cat_id is null or location is null),
  constraint medical_items_period_check check (start_date is null or end_date is null or start_date <= end_date)
);

-- 收尾：這一班離開前一定要勾完的清單，每一項整班勾一次（全員也是）。
-- 位置多一個「貓屋」＝整間屋子、跟貓無關的事（倒垃圾、關冷氣）
create table public.required_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('貓屋', '客廳', '房間', '倉庫', '隔離區')),
  content     text not null,
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint required_items_target_check check (cat_id is null or location is null),
  constraint required_items_period_check check (start_date is null or end_date is null or start_date <= end_date)
);

-- 觀察：剛到班時要拍照的事（拍剩食、拍貓砂、其他），在觀察分頁提醒。不用打勾：
-- 這一班、這隻貓的觀察照片有對應類型就算完成（規則在 composables/observeItems.js）。content 是說明，「其他」必填
create table public.observe_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  category    text not null check (category in ('拍剩食', '拍貓砂', '其他')),
  content     text not null default '',
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint observe_items_target_check check (cat_id is null or location is null),
  constraint observe_items_period_check check (start_date is null or end_date is null or start_date <= end_date)
);

