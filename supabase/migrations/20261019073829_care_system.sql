-- updated_at 由資料庫自動更新，程式不用自己帶
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ── 貓咪 ───────────────────────────────────────────
create table public.cat_profiles (
  id          bigint generated by default as identity primary key,
  name        text not null,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  adopted     boolean not null default false,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ── 飲食／醫療／收尾 ───────────────────────────────
-- 對象：cat_id 有值 = 那隻貓；location 有值 = 那個位置；兩個都空 = 全員（不能同時有值）
-- 期間：start_date / end_date 空代表不限。刪掉貓會連帶刪掉牠的項目，不會變成全員

-- 飲食：只看不打勾，只有「隨餐藥」（拌進飯裡、放碗就可以走）要在備餐分頁打勾
create table public.diet_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  category    text not null check (category in ('乾乾', '罐罐', '隨餐藥', '補充品', '其他')),
  content     text not null,
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint diet_items_target_check check (cat_id is null or location is null),
  constraint diet_items_period_check check (start_date is null or end_date is null or start_date <= end_date)
);

-- 醫療：醫療、餵藥（親手讓牠吃下去）、外用（擦、點、噴），都在醫療分頁打勾
create table public.medical_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('客廳', '房間', '倉庫', '隔離區')),
  category    text not null check (category in ('醫療', '餵藥', '外用')),
  treatment   text not null,
  reason      text,
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint medical_items_target_check check (cat_id is null or location is null),
  constraint medical_items_period_check check (start_date is null or end_date is null or start_date <= end_date)
);

-- 收尾：這一班離開前一定要勾完的清單，每一項整班勾一次（全員也是）。
-- 位置多一個「貓屋」＝整間屋子、跟貓無關的事（倒垃圾、關冷氣）
create table public.required_items (
  id          bigint generated by default as identity primary key,
  cat_id      bigint references public.cat_profiles (id) on delete cascade,
  location    text check (location in ('貓屋', '客廳', '房間', '倉庫', '隔離區')),
  content     text not null,
  shift       text not null default 'both' check (shift in ('morning', 'night', 'both')),
  start_date  date,
  end_date    date,
  sort_order  integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint required_items_target_check check (cat_id is null or location is null),
  constraint required_items_period_check check (start_date is null or end_date is null or start_date <= end_date)
);

create index diet_items_cat_id_idx     on public.diet_items (cat_id);
create index medical_items_cat_id_idx  on public.medical_items (cat_id);
create index required_items_cat_id_idx on public.required_items (cat_id);

-- ── 值班記錄 ───────────────────────────────────────
-- 一班一筆。cats / tasks 是這一班的快照，用以 id 為 key 的物件（結構見 server/utils/shift.js），
-- 寫入只更新改動的那一格（shift_apply），兩人同時改不同的貓或項目不會互相覆蓋。
-- reports = { 分頁: { user_id: { name, text, at } } }：每個分頁、每個人一段回報
create table public.shifts (
  id          bigint generated by default as identity primary key,
  date        date not null,
  shift       text not null check (shift in ('morning', 'night')),
  cats        jsonb not null default '{}'::jsonb,
  tasks       jsonb not null default '{}'::jsonb,
  reports     jsonb not null default '{}'::jsonb,
  updated_by  uuid references auth.users (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (date, shift)
);

-- 只新增、不覆寫，所以獨立一張表，不放進 shifts 的 jsonb
create table public.shift_comments (
  id           bigint generated by default as identity primary key,
  shift_id     bigint not null references public.shifts (id) on delete cascade,
  cat_id       bigint not null references public.cat_profiles (id) on delete cascade,
  tab          text not null check (tab in ('arrive', 'care', 'leave', 'required')),
  body         text not null,
  for_next     boolean not null default false,
  author_name  text,
  created_by   uuid references auth.users (id) on delete set null,
  created_at   timestamptz not null default now()
);

create index shift_comments_shift_id_idx on public.shift_comments (shift_id);

