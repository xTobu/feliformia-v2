-- ── 值班記錄 ───────────────────────────────────────
-- 一班一筆。cats / tasks 是這一班的快照，用以 id 為 key 的物件（結構見 server/utils/shift.js），
-- 寫入只更新改動的那一格（shift_apply），兩人同時改不同的貓或項目不會互相覆蓋。
-- reports = { 分頁: { user_id: { name, text, at } } }：每個分頁、每個人一段回報
create table public.shifts (
  id          bigint generated by default as identity primary key,
  date        date not null,
  shift       text not null check (shift in ('morning', 'night')),
  cats        jsonb not null default '{}'::jsonb,
  tasks       jsonb not null default '{}'::jsonb,
  reports     jsonb not null default '{}'::jsonb,
  updated_by  uuid references auth.users (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (date, shift)
);

-- 留言：一隻貓、一個分頁是一個頻道，跨班一路往上看（班與班之間有分隔線）。
-- 獨立一張表，不放進 shifts 的 jsonb。只附照片時 body 是空字串；作者可以改文字（edited_at 記最後一次）或刪掉
create table public.shift_comments (
  id           bigint generated by default as identity primary key,
  shift_id     bigint not null references public.shifts (id) on delete cascade,
  cat_id       bigint not null references public.cat_profiles (id) on delete cascade,
  tab          text not null check (tab in ('arrive', 'care', 'meal', 'required')),
  body         text not null,
  for_next     boolean not null default false,
  author_name  text,
  created_by   uuid references auth.users (id) on delete set null,
  created_at   timestamptz not null default now(),
  edited_at    timestamptz
);

create index shift_comments_shift_id_idx on public.shift_comments (shift_id);
create index shift_comments_channel_idx on public.shift_comments (cat_id, tab, created_at);

-- 照片：檔案在 Storage（shift-photos bucket，私人），這裡記是哪一班、哪隻貓、哪個分頁、誰傳的。
