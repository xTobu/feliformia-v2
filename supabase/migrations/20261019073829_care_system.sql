-- ── 局部更新 ───────────────────────────────────────
-- 在 jsonb 物件裡照路徑設值，中間缺的層會自動補成 {}。
-- p_if_missing = true 時，那個位置已經有值就不動（用來補貓的基本資料，不蓋掉已填的內容）
create or replace function public.jsonb_deep_set(
  p_target jsonb,
  p_path text[],
  p_value jsonb,
  p_if_missing boolean default false
)
returns jsonb
language plpgsql
immutable
set search_path = ''
as $$
declare
  result jsonb := coalesce(p_target, '{}'::jsonb);
  depth int := coalesce(array_length(p_path, 1), 0);
begin
  if depth = 0 then
    return p_value;
  end if;
  if p_if_missing and result #> p_path is not null then
    return result;
  end if;
  for i in 1 .. depth - 1 loop
    if jsonb_typeof(result #> p_path[1:i]) is distinct from 'object' then
      result := jsonb_set(result, p_path[1:i], '{}'::jsonb, true);
    end if;
  end loop;
  return jsonb_set(result, p_path, p_value, true);
end;
$$;

-- 套用一批改動。p_ops 每一項：{ "column": "cats" | "tasks" | "reports", "path": [...], "value": ..., "if_missing": false }
-- select ... for update 鎖住這一班，同時進來的請求會排隊，一個一個套用
create or replace function public.shift_apply(
  p_shift_id bigint,
  p_ops jsonb,
  p_user uuid
)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v_cats jsonb;
  v_tasks jsonb;
  v_reports jsonb;
  op jsonb;
  v_path text[];
  v_if_missing boolean;
begin
  select cats, tasks, reports
    into v_cats, v_tasks, v_reports
    from public.shifts
   where id = p_shift_id
     for update;

  if not found then
    raise exception 'shift % not found', p_shift_id;
  end if;

  for op in select * from jsonb_array_elements(p_ops) loop
    v_path := array(select jsonb_array_elements_text(coalesce(op -> 'path', '[]'::jsonb)));
    v_if_missing := coalesce((op ->> 'if_missing')::boolean, false);
    case op ->> 'column'
      when 'cats' then
        v_cats := public.jsonb_deep_set(v_cats, v_path, op -> 'value', v_if_missing);
      when 'tasks' then
        v_tasks := public.jsonb_deep_set(v_tasks, v_path, op -> 'value', v_if_missing);
      when 'reports' then
        v_reports := public.jsonb_deep_set(v_reports, v_path, op -> 'value', v_if_missing);
      else
        raise exception 'unknown column %', op ->> 'column';
    end case;
  end loop;

  update public.shifts
     set cats = v_cats,
         tasks = v_tasks,
         reports = v_reports,
         updated_by = p_user
   where id = p_shift_id;
end;
$$;

-- public schema 的函式預設誰都能透過 API 呼叫，收回來只留給 service_role
revoke execute on function public.shift_apply(bigint, jsonb, uuid) from public, anon, authenticated;
grant execute on function public.shift_apply(bigint, jsonb, uuid) to service_role;

-- ── 初始資料：舊 cats 複製一份到 cat_profiles，沿用原本的 id ──
